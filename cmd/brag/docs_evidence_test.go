package main

import (
	"os"
	"path/filepath"
	"testing"
)

func TestDocumentationSnapshotCoverageAndGeneratedComparisons(t *testing.T) {
	d := t.TempDir()
	gitCmd(t, d, "init", "-q", "-b", "main")
	gitCmd(t, d, "config", "user.name", "Docs")
	gitCmd(t, d, "config", "user.email", "docs@example.test")
	write := func(path, src string) {
		t.Helper()
		full := filepath.Join(d, path)
		if err := os.MkdirAll(filepath.Dir(full), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(src), 0600); err != nil {
			t.Fatal(err)
		}
	}
	write("p.go", `// Package p documents package p.
package p
// Public documents a function.
func Public() {}
type API interface {
 // Call documents a method.
 Call()
 Missing()
}
// Pair documents two vars.
var A, B int
`)
	write("README.md", "# Old docs\n")
	write("generated.md", "// Code generated by local; DO NOT EDIT.\n# Generated\n")
	write("output.html", "<!-- Code generated by htmlgen; DO NOT EDIT. -->\n<p>Generated</p>\n")
	write("templates/example.tmpl", "{{.Name}}\n")
	write("gen.go", "//go:generate go run ./cmd/gen\n// Code generated by gen; DO NOT EDIT.\npackage p\nfunc Generated() {}\n")
	gitCmd(t, d, "add", ".")
	gitCmd(t, d, "commit", "-qm", "base")
	base := gitCmd(t, d, "rev-parse", "HEAD")
	write("p.go", `// Package p documents package p.
package p
func Public() {}
type API interface { Call(); Missing() }
// Pair documents two vars.
var A, B int
`)
	write("README.md", "# Updated docs\n")
	write("new.rst", "New text\n")
	gitCmd(t, d, "add", ".")
	gitCmd(t, d, "commit", "-qm", "head")
	head := gitCmd(t, d, "rev-parse", "HEAD")
	write("new.rst", "Changed tracked docs\n")
	e := buildDocumentationEvidence(d, []snapshotInput{{label: "baseline", rev: base}, {label: "HEAD", rev: head}, {label: "current_tracked_worktree", rev: head, overlay: true}})
	if e.Status != "measured" || len(e.Snapshots) != 3 {
		t.Fatalf("docs=%+v", e)
	}
	b, h, c := e.Snapshots[0].Counts, e.Snapshots[1].Counts, e.Snapshots[2].Counts
	if b.PackageCount != 1 || b.PackagesWithComments != 1 || b.ExportedSymbols != 5 || b.ExportedSymbolsDocumented != 3 || b.ExportedInterfaceMethods != 2 || b.ExportedInterfaceMethodsDocumented != 1 {
		t.Fatalf("Go doc coverage=%+v", b)
	}
	if b.GoGenerateFiles != 1 || b.GoGenerateDirectives != 1 || b.GeneratedGo != 1 || b.TemplateConfigFiles != 1 || b.MarkedGenerated != 2 || b.UnknownGeneration != 1 {
		t.Fatalf("generated inventory=%+v", b)
	}
	if e.Comparisons[0].Modified != 1 || e.Comparisons[0].Added != 1 || e.Comparisons[1].Modified != 1 {
		t.Fatalf("doc comparisons=%+v", e.Comparisons)
	}
	if h.MarkedGenerated != 2 || c.MarkedGenerated != 2 {
		t.Fatal("generated markers should be recognized without running generators")
	}
}
