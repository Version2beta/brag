func TestMutationManifestWriteFailureDoesNotExecuteTests(t *testing.T) {
	d, _ := mkRepo(t)
	writeMutationFixture(t, d, "package app\nfunc F(x int)bool{return x<2}\n", "package app\nimport \"testing\"\nfunc TestF(t *testing.T){if !F(1){t.Fatal(\"bad\")}}\n")
	artifact := privateTempDir(t)
	if err := os.Chmod(artifact, 0500); err != nil {
		t.Fatal(err)
	}
	defer os.Chmod(artifact, 0700)
	probe := filepath.Join(artifact, "write-probe")
	if err := os.WriteFile(probe, []byte("x"), 0600); err == nil {
		os.Remove(probe)
		t.Skip("filesystem owner can write mode-0500 directory")
	}
	marker := filepath.Join(t.TempDir(), "go-test-executed")
	realGo, err := exec.LookPath("go")
	if err != nil {
		t.Fatal(err)
	}
	wrapper, script := t.TempDir(), ""
	script = filepath.Join(wrapper, "go")
	body := "#!/bin/sh\ncase \"$*\" in *\"test -json\"*) touch \"" + marker + "\";; esac\nexec \"" + realGo + "\" \"$@\"\n"
	if err = os.WriteFile(script, []byte(body), 0700); err != nil {
		t.Fatal(err)
	}
	oldPath := os.Getenv("PATH")
	if err = os.Setenv("PATH", wrapper+string(os.PathListSeparator)+oldPath); err != nil {
		t.Fatal(err)
	}
	defer os.Setenv("PATH", oldPath)
	r := runMutationTests(context.Background(), "all", gitCmd(t, d, "rev-parse", "HEAD"), nil, d, 4, 20*time.Second, time.Minute, artifact, nil, nil, nil)
	if len(r.Snapshots) != 1 {
		t.Fatalf("report=%+v", r)
	}
	s := r.Snapshots[0]
	if s.Status != "inconclusive" || s.Score != nil || s.Counts["killed"] != 0 || s.Counts["survived"] != 0 {
		t.Fatalf("manifest failure evidence=%+v", s)
	}
	if _, err = os.Stat(marker); !os.IsNotExist(err) {
		t.Fatalf("go test executed without manifest, marker err=%v", err)
	}
}
