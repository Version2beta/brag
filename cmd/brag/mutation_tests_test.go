func TestMutationSitesStableGeneratedBuildAndFilters(t *testing.T) {
	entries := []snapshotEntry{{path: "go.mod", data: []byte("module example.test/mod\n\ngo 1.22\n")}, {path: "app.go", data: []byte("package app\nfunc F(x int) bool { return x < 3 && true }\n")}, {path: "sub/app.go", data: []byte("package sub\nfunc G(x int) bool{return x >= 1}\n")}, {path: "app_test.go", data: []byte("package app\n")}, {path: "generated.go", data: []byte("// Code generated by fixture. DO NOT EDIT.\npackage app\nfunc H() bool{return false}\n")}, {path: "tagged.go", data: []byte("//go:build custom\npackage app\nfunc X(x int)bool{return x>0}\n")}}
	a, known, partial, skipped, err := mutationSites(entries, nil, nil)
	if err != nil || partial || known != 3 {
		t.Fatalf("sites: %v partial=%v known=%d", err, partial, known)
	}
	b, _, _, _, _ := mutationSites(entries, nil, nil)
	if !equalMutationIDs(a, b) {
		t.Fatal("IDs changed")
	}
	if len(a) != 3 {
		t.Fatalf("sites=%+v", a)
	}
	pkg, _, _, _, err := mutationSites(entries, []string{"example.test/mod/sub"}, nil)
	if err != nil || len(pkg) != 1 || pkg[0].Path != "sub/app.go" {
		t.Fatalf("package: %+v %v", pkg, err)
	}
	ps, _, _, _, _ := mutationSites(entries, nil, []string{"sub"})
	if len(ps) != 1 {
		t.Fatalf("path sites=%d", len(ps))
	}
	if len(skipped) != 4 {
		t.Fatalf("skipped=%v", skipped)
	}
	if _, _, _, _, err := mutationSites([]snapshotEntry{{path: "x.go", data: []byte("package x")}}, []string{"example.test/x"}, nil); err == nil {
		t.Fatal("no module path accepted")
	}
}
