func TestMutationBranchSnapshotsAndUntrackedExclusion(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping multi-snapshot mutation test-suite execution in short mode")
	}
	d, _ := mkRepo(t)
	writeMutationFixture(t, d, "package app\nfunc F(x int)bool{return x<2}\n", "package app\nimport \"testing\"\nfunc TestF(t *testing.T){if !F(1){t.Fatal(\"bad\")}}\n")
	base := gitCmd(t, d, "rev-parse", "HEAD")
	os.WriteFile(filepath.Join(d, "app.go"), []byte("package app\nfunc F(x int)bool{return x>0}\n"), 0600)
	gitCmd(t, d, "add", "app.go")
	gitCmd(t, d, "commit", "-qm", "head change")
	head := gitCmd(t, d, "rev-parse", "HEAD")
	os.WriteFile(filepath.Join(d, "untracked.go"), []byte("package app\nfunc U(x int)bool{return x<9}\n"), 0600)
	r := runMutationTests(context.Background(), "branch", head, &baseInfo{MergeBase: base}, d, 1, 30*time.Second, 4*time.Minute, privateTempDir(t), nil, nil, []string{"baseline", "HEAD", "current_tracked_worktree"})
	if len(r.Snapshots) != 3 {
		t.Fatalf("snapshots=%+v", r)
	}
	want := []string{"baseline", "HEAD", "current_tracked_worktree"}
	for i, s := range r.Snapshots {
		if s.Name != want[i] {
			t.Fatalf("order=%+v", r.Snapshots)
		}
		var m mutationManifest
		if e := json.Unmarshal(mustRead(t, s.ManifestArtifact), &m); e != nil {
			t.Fatal(e)
		}
		for _, site := range m.Sites {
			if site.Path == "untracked.go" {
				t.Fatal("untracked file included")
			}
		}
	}
	if r.Snapshots[0].SourceIdentity == r.Snapshots[1].SourceIdentity {
		t.Fatal("baseline and HEAD identities equal")
	}
}
