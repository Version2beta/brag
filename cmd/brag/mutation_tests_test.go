func TestParseMutationEventsFailsClosedAcrossPackages(t *testing.T) {
	stream := []byte("{\"Action\":\"start\",\"Package\":\"example.test/a\"}\n{\"Action\":\"fail\",\"Package\":\"example.test/a\",\"Test\":\"TestBad\"}\n{\"Action\":\"fail\",\"Package\":\"example.test/a\"}\n{\"Action\":\"start\",\"Package\":\"example.test/b\"}\n{\"Action\":\"output\",\"Package\":\"example.test/b\",\"Output\":\"# example.test/b\\\\n\"}\n{\"Action\":\"fail\",\"Package\":\"example.test/b\"}\n")
	_, complete, failed := parseMutationEvents(stream)
	if !complete || failed {
		t.Fatalf("mixed test/build failures classified as kill: complete=%v failed=%v", complete, failed)
	}
	valid := []byte(`{"Action":"start","Package":"example.test/a"}
{"Action":"run","Package":"example.test/a","Test":"TestBad"}
{"Action":"output","Package":"example.test/a","Test":"TestBad","Output":"--- FAIL: TestBad (0.00s)\n"}
{"Action":"fail","Package":"example.test/a","Test":"TestBad"}
{"Action":"output","Package":"example.test/a","Output":"FAIL\n"}
{"Action":"output","Package":"example.test/a","Output":"FAIL\texample.test/a\t0.001s\n"}
{"Action":"fail","Package":"example.test/a"}
`)
	_, complete, failed = parseMutationEvents(valid)
	if !complete || !failed {
		t.Fatalf("valid test failure rejected: %v %v", complete, failed)
	}
	if !mutationFailureIsAccounted(valid, nil, failed) {
		t.Fatal("complete test failure was not accepted")
	}
	if mutationFailureIsAccounted(valid, []byte("go: setup failure"), failed) {
		t.Fatal("stderr setup failure masked by test failure")
	}
	mixedInfrastructure := []byte(`{"Action":"start","Package":"example.test/a"}
{"Action":"run","Package":"example.test/a","Test":"TestBad"}
{"Action":"output","Package":"example.test/a","Test":"TestBad","Output":"--- FAIL: TestBad (0.00s)\n"}
{"Action":"fail","Package":"example.test/a","Test":"TestBad"}
{"Action":"output","Package":"example.test/a","Output":"worker pool disappeared\n"}
{"Action":"output","Package":"example.test/a","Output":"FAIL\texample.test/a\t0.001s\n"}
{"Action":"fail","Package":"example.test/a"}
`)
	if mutationFailureIsAccounted(mixedInfrastructure, nil, true) {
		t.Fatal("unknown package-level infrastructure output was accepted")
	}
	withCompile := append(append([]byte{}, valid...), []byte(`{"Action":"output","Package":"example.test/a","Output":"undefined: missing\n"}`)...)
	if mutationFailureIsAccounted(withCompile, nil, failed) {
		t.Fatal("compile evidence masked by test failure")
	}
	_, complete, failed = parseMutationEvents([]byte("{\"Action\":\"start\",\"Package\":\"example.test/a\"}\n{\"Action\":\"fail\",\"Package\":\"example.test/a\",\"Test\":\"TestBad\"}\n"))
	if complete || failed {
		t.Fatalf("test failure without package terminal accepted: %v %v", complete, failed)
	}
	_, complete, _ = parseMutationEvents([]byte(`{"Action":"fail"}`))
	if complete {
		t.Fatal("invalid JSON event accepted")
	}
}
func TestMutationBooleanSitesOnlyUsePredeclaredConstants(t *testing.T) {
	cases := []struct {
		name, src string
		want      int
		before    string
	}{
		{"literal", "package p\nfunc F()bool{return true}\n", 1, "true"},
		{"local_shadow", "package p\nfunc F()bool{ true := false; return true }\n", 1, "false"},
		{"package_shadow", "package p\nvar true = false\nfunc F()bool{return true}\n", 1, "false"},
		{"selector", "package p\ntype T struct{ true bool }; func F(x T)bool{return x.true}\n", 0, ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			entries := []snapshotEntry{{path: "go.mod", data: []byte("module example.test/p\ngo 1.22\n")}, {path: "p.go", data: []byte(tc.src)}}
			sites, _, _, _, err := mutationSites(entries, nil, nil)
			if err != nil {
				t.Fatal(err)
			}
			var boolSites []mutationSite
			for _, s := range sites {
				if s.Before == "true" || s.Before == "false" {
					boolSites = append(boolSites, s)
				}
			}
			if len(boolSites) != tc.want {
				t.Fatalf("boolean sites=%+v want %d", boolSites, tc.want)
			}
			if tc.want > 0 && boolSites[0].Before != tc.before {
				t.Fatalf("site=%+v want before=%s", boolSites[0], tc.before)
			}
		})
	}
}
